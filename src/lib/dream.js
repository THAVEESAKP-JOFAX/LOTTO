// "ฝันเห็นงูรัด" → "งูรัด"
export function dreamSubject(text) {
  let t = String(text).replace(/\s+/g, '');
  // ตัดคำนำหน้าซ้ำได้หลายชั้น เช่น "ทำนายฝัน ฝันว่า…"
  for (let prev = ''; prev !== t;) { prev = t; t = t.replace(/^(?:เลข|ทำนายฝัน|ทำนานฝัน|ทํานายฝัน|ตีเลขฝัน|ฝัน|ว่า|เห็น|ถึง)/, ''); }
  return t.replace(/[^ก-๙0-9a-z]/gi, '').slice(0, 40);
}

const pad2 = (n) => String(n % 100).padStart(2, '0');
const root = (n) => (n === 0 ? 0 : 1 + ((n - 1) % 9));

export function dreamNumbers(subject) {
  const values = [...subject].map((c) => (/\d/.test(c) ? Number(c) : VALUE[c])).filter((v) => v !== undefined);
  const total = values.reduce((a, b) => a + b, 0);
  const r = root(total);
  const main = [...new Set([r, total % 10, values[0] ?? r])];
  // คู่ / สามตัวจากค่าตัวอักษรที่ติดกัน + เลขจากผลรวม
  const pairs = values.slice(1).map((v, i) => `${values[i]}${v}`);
  const two = [...new Set([pad2(total), pad2(total).split('').reverse().join(''), `${r}${total % 10}`, ...pairs])].slice(0, 6);
  const triples = values.slice(2).map((v, i) => `${values[i]}${values[i + 1]}${v}`);
  const three = [...new Set([`${r}${pad2(total)}`, ...triples, `${pad2(total)}${r}`])].slice(0, 4);
  return { values, total, main, two, three };
}

export function interpretDream(text) {
  const subject = dreamSubject(text);
  if (!subject) return null;
  const all = DREAMS.flatMap((d) => d.words.map((w) => [w, d])).sort((a, b) => b[0].length - a[0].length);
  const found = [];
  let rest = subject;
  for (const [w, d] of all) {
    if (rest.includes(w) && !found.includes(d)) { found.push(d); rest = rest.replace(w, ' '); }
    if (found.length === 2) break;
  }
  return { subject, found, ...dreamNumbers(subject) };
}
